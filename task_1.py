# --- Часть 1. Выражение без вывода ---
# В REPL результат этого выражения был бы напечатан автоматически,
# но при запуске файла он вычисляется и отбрасывается.
'''2 + 3 * 4'''

# --- То же выражение, обёрнутое в print() ---
print(2 + 3 * 4)

# --- Часть 2. Выражения, инструкции, литералы, имена ---
course = "Python"                     # инструкция присваивания
hours = 4 * 2                         # инструкция; справа — выражение
print(f"{course}: {hours} часов")     # инструкция; внутри — вызов print()